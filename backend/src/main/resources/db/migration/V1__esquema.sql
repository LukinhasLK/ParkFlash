-- Esquema inicial do ParkFlash (compatível com H2 e PostgreSQL).

CREATE TABLE unidade (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL UNIQUE,
    endereco VARCHAR(200) NOT NULL,
    telefone VARCHAR(20)
);

CREATE TABLE manobrista (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    telefone VARCHAR(20),
    cpf      VARCHAR(14)
);

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    nivel      VARCHAR(20)  NOT NULL,
    senha_hash VARCHAR(100) NOT NULL
);

CREATE TABLE socio (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE socio_participacao (
    socio_id   BIGINT        NOT NULL REFERENCES socio (id) ON DELETE CASCADE,
    unidade_id BIGINT        NOT NULL REFERENCES unidade (id),
    percentual NUMERIC(5, 2) NOT NULL,
    PRIMARY KEY (socio_id, unidade_id)
);

CREATE TABLE ficha (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data              DATE           NOT NULL,
    unidade_id        BIGINT         NOT NULL REFERENCES unidade (id),
    turno             VARCHAR(10)    NOT NULL,
    ficha_inicio      INTEGER        NOT NULL,
    ficha_fim         INTEGER        NOT NULL,
    fichas_canceladas INTEGER        NOT NULL,
    total_carros      INTEGER        NOT NULL,
    valor_dinheiro    NUMERIC(12, 2) NOT NULL,
    valor_cartao      NUMERIC(12, 2) NOT NULL,
    taxa_maquininha   NUMERIC(5, 2)  NOT NULL,
    total_bruto       NUMERIC(12, 2) NOT NULL,
    total_liquido     NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uk_ficha_data_unidade_turno UNIQUE (data, unidade_id, turno)
);

CREATE TABLE ficha_manobrista (
    ficha_id      BIGINT         NOT NULL REFERENCES ficha (id) ON DELETE CASCADE,
    ordem         INTEGER        NOT NULL,
    manobrista_id BIGINT         NOT NULL REFERENCES manobrista (id),
    diaria        NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (ficha_id, ordem),
    CONSTRAINT uk_ficha_manobrista UNIQUE (ficha_id, manobrista_id)
);

CREATE TABLE ficha_despesa (
    ficha_id  BIGINT         NOT NULL REFERENCES ficha (id) ON DELETE CASCADE,
    ordem     INTEGER        NOT NULL,
    descricao VARCHAR(200)   NOT NULL,
    valor     NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (ficha_id, ordem)
);

CREATE TABLE despesa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data       DATE           NOT NULL,
    unidade_id BIGINT         NOT NULL REFERENCES unidade (id),
    categoria  VARCHAR(20)    NOT NULL,
    descricao  VARCHAR(200)   NOT NULL,
    valor      NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_ficha_data ON ficha (data);
CREATE INDEX idx_despesa_data ON despesa (data);
